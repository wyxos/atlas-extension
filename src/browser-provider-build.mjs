import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const idPattern = /^[a-z][a-z0-9-]{0,63}$/;
const portableName = /^[a-zA-Z0-9][a-zA-Z0-9._-]*$/;

function readFiles(directory, prefix = '') {
  return fs.readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name)).flatMap(entry => {
      if (!portableName.test(entry.name) || entry.isSymbolicLink()) {
        throw new Error('Browser provider contains an unsafe source path.');
      }
      if (['node_modules', 'target', '.git'].includes(entry.name)) return [];
      const relative = `${prefix}${entry.name}`;
      if (entry.isDirectory()) return readFiles(path.join(directory, entry.name), `${relative}/`);
      if (!entry.isFile()) throw new Error('Browser provider contains a non-file source.');
      return [relative];
    });
}

// Explicit local, reviewed source inputs only. This runs at extension build time;
// the installed MV3 extension never fetches or evaluates plugin code remotely.
export function syncBrowserProviders({ root, sources }) {
  if (!Array.isArray(sources) || sources.length === 0 || sources.length > 64) {
    throw new Error('Provide between one and 64 browser provider source directories.');
  }
  const output = path.join(root, 'src/provider-plugins');
  const providers = sources.map(source => {
    const directory = path.resolve(root, source);
    if (fs.lstatSync(directory).isSymbolicLink()) throw new Error('Provider source cannot be a symlink.');
    const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'browser-provider.json'), 'utf8'));
    if (manifest.schemaVersion !== 1 || !idPattern.test(manifest.id) || manifest.entry !== 'index.js') {
      throw new Error('Unsupported browser provider manifest.');
    }
    const files = readFiles(directory).map(relative => {
      const bytes = fs.readFileSync(path.join(directory, relative));
      if (bytes.length > 2 * 1024 * 1024) throw new Error('Browser source file exceeds the build limit.');
      return { relative, bytes, sha256: digest(bytes) };
    });
    if (!files.some(file => file.relative === manifest.entry)) throw new Error('Missing browser entry point.');
    return { id: manifest.id, files };
  }).sort((a, b) => a.id.localeCompare(b.id));
  if (new Set(providers.map(provider => provider.id)).size !== providers.length) {
    throw new Error('Duplicate browser provider id.');
  }
  // Validate the complete selection before modifying the generated snapshot.
  fs.mkdirSync(output, { recursive: true });
  for (const provider of providers) {
    for (const file of provider.files) {
      const destination = path.join(output, 'packages', provider.id, file.relative);
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, file.bytes);
    }
  }
  const imports = providers.map((provider, i) => `import provider${i} from './packages/${provider.id}/index.js';`);
  const registry = [
    '// Generated by scripts/sync-browser-providers.mjs; edit the provider source repositories.',
    "import { createBrowserProviderRegistry } from './contract.js';",
    ...imports,
    `export const browserProviders = createBrowserProviderRegistry([${providers.map((_, i) => `provider${i}`).join(', ')}]);`,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(output, 'registry.js'), registry);
  const lock = {
    schemaVersion: 1,
    registrySha256: digest(registry),
    providers: providers.map(provider => ({
      id: provider.id,
      files: Object.fromEntries(provider.files.map(file => [file.relative, file.sha256])),
    })),
  };
  fs.writeFileSync(path.join(output, 'sources.lock.json'), `${JSON.stringify(lock, null, 2)}\n`);
  return providers.map(provider => provider.id);
}

export function verifyBrowserProviders(root) {
  const directory = path.join(root, 'src/provider-plugins');
  const lock = JSON.parse(fs.readFileSync(path.join(directory, 'sources.lock.json'), 'utf8'));
  if (lock.schemaVersion !== 1 || !Array.isArray(lock.providers)
    || digest(fs.readFileSync(path.join(directory, 'registry.js'))) !== lock.registrySha256) {
    throw new Error('Browser provider registry differs from its source lock; sync reviewed sources.');
  }
  for (const provider of lock.providers) {
    if (!idPattern.test(provider.id)) throw new Error('Invalid provider source lock.');
    for (const [relative, hash] of Object.entries(provider.files)) {
      if (relative.split('/').some(segment => !portableName.test(segment) || segment === '..')) {
        throw new Error('Invalid provider source lock path.');
      }
      if (digest(fs.readFileSync(path.join(directory, 'packages', provider.id, relative))) !== hash) {
        throw new Error('Browser provider source differs from its lock; sync reviewed sources.');
      }
    }
  }
  return lock.providers.map(provider => provider.id);
}

export function prepareBrowserProviders(root, env = process.env) {
  if (env.ATLAS_BROWSER_PROVIDER_SOURCES) {
    syncBrowserProviders({ root, sources: JSON.parse(env.ATLAS_BROWSER_PROVIDER_SOURCES) });
  }
  return verifyBrowserProviders(root);
}
